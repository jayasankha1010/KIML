"""
Run XGDAG end to end on one of OUR diseases.

XGDAG's own entry points cannot do this. CreateGraph.py is a module with no
__main__ block; TrainerScript.py hardcodes both a disease list and the DIAMOnD
paths; ComputeRankingScript.py hardcodes a disease list of CUIDs. Rather than
patch three files, this calls the same library functions directly.

THE from_diamond FLAG MEANS TWO DIFFERENT THINGS, which is the trap here:

  create_graph_from_PPI(..., from_diamond=)   selects the PPI FILE FORMAT
      False -> raw BioGRID TSV, needs 'Organism ID Interactor A' columns, and
               rewrites '-' and '.' in gene symbols to '_'
      True  -> plain "gene1 gene2" lines, symbols untouched

  get_dataset_from_graph(..., from_diamond=)  selects the DATASET DIRECTORY
      False -> Datasets/
      True  -> Datasets/Diamond_dataset/

We need True for the graph and False for the dataset. Our PPI is NIAPU's
"gene1 gene2" file - the same one the NeDBIT features were computed from - so
the format flag must be True, and the symbol rewriting in the other branch
would silently break alignment with those features (NKX2-1 would become
NKX2_1 in the graph but stay NKX2-1 in the features). Our seeds, features and
ranking live in Datasets/, so the directory flag must be False.

Inputs expected in XGDAG/Datasets/ (generated by run_nedbit.sh):
    <disease>_seed_genes.txt    gene score
    <disease>_features          name,class,degree,ring,NetRank,...
    <disease>_ranking           gene score label

Usage:
    python run_disease.py dee --ppi /path/to/NIAPU/data/biogrid_...txt
    python run_disease.py dee --skip-train          # reuse an existing model
"""

import argparse
import os
import sys
from time import perf_counter

from CreateGraph import create_graph_from_PPI
from CreateDatasetv2 import get_dataset_from_graph
from GraphSageModel import GNN7L_Sage
from GNNTrain import train, predict_from_saved_model
from GDARanking import predict_candidate_genes
from Paths import PATH_TO_DATASETS, PATH_TO_GRAPHS, PATH_TO_RANKINGS

CLASSES = ['P', 'LP', 'WN', 'LN', 'RN']


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("disease")
    parser.add_argument("--ppi",
                        default="/data/gpfs/projects/punim2353/chathura/tools/"
                                "NIAPU/data/biogrid_gene_pairs_clean_Hs_4_4_206.txt")
    parser.add_argument("--method", default="gnnexplainer")
    parser.add_argument("--num-cpus", type=int, default=4)
    parser.add_argument("--epochs", type=int, default=40000)
    parser.add_argument("--lr", type=float, default=0.001)
    parser.add_argument("--weight-decay", type=float, default=0.0005)
    parser.add_argument("--skip-train", action="store_true",
                        help="reuse the saved model instead of retraining")
    args = parser.parse_args()

    disease = args.disease
    started = perf_counter()

    # Fail now, with a readable message, rather than deep inside pandas.
    for suffix in ("_seed_genes.txt", "_features", "_ranking"):
        path = os.path.join(PATH_TO_DATASETS, disease + suffix)
        if not os.path.exists(path):
            print("[Error] missing input: {}".format(path))
            print("        Generate it with run_nedbit.sh, then copy into")
            print("        XGDAG/Datasets/ alongside the seed file.")
            return 1
    if not os.path.exists(args.ppi):
        print("[Error] PPI not found: {}".format(args.ppi))
        return 1

    graph_name = "grafo_nedbit_" + disease
    graph_path = os.path.join(PATH_TO_GRAPHS, graph_name + ".gml")

    if os.path.exists(graph_path):
        print("[=] graph exists, reusing: {}".format(graph_path))
    else:
        print("[+] building graph from {}".format(args.ppi))
        # from_diamond=True: our PPI is "gene1 gene2", and this branch leaves
        # gene symbols alone. See the module docstring.
        create_graph_from_PPI(args.ppi, disease, graph_name, from_diamond=True)

    print("[+] building dataset")
    # from_diamond=False: our per-disease files are in Datasets/, not
    # Datasets/Diamond_dataset/.
    dataset, G = get_dataset_from_graph(graph_path, disease, quartile=False,
                                        from_diamond=False)

    model_name = "GraphSAGE_" + disease
    if args.skip_train:
        print("[=] skipping training, loading {}".format(model_name))
        preds, _, model = predict_from_saved_model(
            model_name, dataset, CLASSES, save_to_file=False)
    else:
        print("[+] training {} for {} epochs".format(model_name, args.epochs))
        model = GNN7L_Sage(dataset)
        preds = train(model, dataset, args.epochs, args.lr, args.weight_decay,
                      CLASSES, model_name)

    print("[+] ranking with {}".format(args.method))
    ranking = predict_candidate_genes(
        model, dataset, preds,
        explainability_method=args.method,
        disease_Id=disease,
        explanation_nodes_ratio=1,
        masks_for_seed=10,
        num_hops=1,
        G=G,
        num_pos="all",
        num_workers=args.num_cpus)

    # Same '_kiml_' convention the patch applies to ComputeRankingScript, so
    # nothing of the authors' is ever overwritten and the provenance is clear
    # from the filename.
    out = os.path.join(PATH_TO_RANKINGS,
                       "{}_kiml_xgdag_{}.txt".format(disease, args.method.lower()))
    with open(out, "w") as handle:
        for line in ranking:
            handle.write(line + "\n")

    print("[+] wrote {} genes -> {}".format(len(ranking), out))
    print("[Success] {} in {:.0f}s".format(disease, perf_counter() - started))
    return 0


if __name__ == "__main__":
    sys.exit(main())
