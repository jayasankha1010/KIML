"""
Generate SPEOS configs, ground-truth mappings and a SLURM manifest for the
Bioinformatics Advances revision runs.

Why this exists
---------------
The KIML repo currently ships three configs (DEE only) and a single
extensions/mapping.json entry (dee_2022_09), but the manuscript reports nine
diseases. As the repo is the public reproducibility artifact, it should be able
to run everything the paper claims. This script fills that gap and, at the same
time, lays out the extra configurations the reviewers asked for.

What it writes
--------------
  extensions/mapping.json    one ground-truth entry per disease
  data/.../AD_DEE-2022_09.txt, AR_DEE-2022_09.txt
                             derived (2025-03 list minus the post-split diff),
                             because no stored 2022-09 list exists for these two
  configs/Rev_*.yaml         disease x variant x seed
  revision_manifest.txt      one config name per line, for the SLURM array

Variants
--------
  GNN     experimental features only, baseline PPI graph      (paper: LL)
  CGNN    PubMed features only, knowledge graph               (paper: HL)
  KIGNN   both feature sets, knowledge graph                  (paper: LL+HL)
  KIGNN-PPI   both feature sets on the BASELINE PPI graph  }  task 5: separates
  GNN-KG      experimental features on the KNOWLEDGE graph  }  features from edges

Seeds
-----
SPEOS seeds only the numpy RNG used for fold assignment (config.crossval.seed);
there is no torch.manual_seed anywhere, so model initialisation varies run to
run regardless. Repeating a configuration therefore yields genuine run-to-run
variance, which is what Reviewer 1 comment 10 asks to see. It also means the
published numbers came from a single unseeded run and cannot be reproduced
exactly - see REPRODUCIBILITY in the README this writes.

Usage (from the KIML root):
    python additional_experiments/revision_runs/make_configs.py --seeds 5
    sbatch --array=0-$(($(wc -l < external/SPEOS/revision_manifest.txt)-1)) \
           additional_experiments/revision_runs/run_revision.slurm
"""

import argparse
import json
import os

GT_PREFIX = "gt_"

# disease key -> (2022-09 ground-truth filename, human label)
DISEASES = {
    "dee": ("DEE-2022_09.txt", "DEE"),
    "ad_dee": ("AD_DEE-2022_09.txt", "AD DEE"),
    "ar_dee": ("AR_DEE-2022_09.txt", "AR DEE"),
    "microcephaly": ("Microcephaly-2022-09.txt", "Microcephaly"),
    "intellectual_disability": ("Intellectual-disability-2022-09.txt", "Intellectual Disability"),
    "mnd": ("MND-2022-09.txt", "Motor Neuron Disease"),
    "cp": ("CP-2022-09.txt", "Cerebral Palsy"),
    "platelet_disorder": ("Bleeding_and_Platelet_Disorders-2022-09.txt", "Bleeding and Platelet Disorder"),
    "arthrogryposis": ("Arthrogryposis-2022-09.txt", "Arthrogryposis"),
}

# AD/AR DEE have no stored 2022-09 list; derive it as (2025-03 list) - (diff).
DERIVED = {
    "ad_dee": ("AD_DEE-2025_03.txt", "AD_DEE-2022_09_to_2025_03.txt", "AD_DEE-2022_09.txt"),
    "ar_dee": ("AR_DEE_2025_03.txt", "AR_DEE-2022_09_to_2025_03.txt", "AR_DEE-2022_09.txt"),
}

# variant -> (datasets json, adjacency list, adjacency_field list)
PPI = ["BioPlex30293T", "BioPlex30HCT116", "HuRI"]
KG = ["pathway", "covaries"]
VARIANTS = {
    "GNN": ("./extensions/datasets_ll.json", PPI),
    "CGNN": ("./extensions/datasets_hl.json", KG),
    "KIGNN": ("./extensions/datasets.json", KG),
    # Reviewer 1 comment 5b: separate the node-feature contribution from the
    # knowledge-graph-edge contribution instead of changing both at once.
    "KIGNN-PPI": ("./extensions/datasets.json", PPI),
    "GNN-KG": ("./extensions/datasets_ll.json", KG),
}

CONFIG_TEMPLATE = """  name: {name}

# Generated by additional_experiments/revision_runs/make_configs.py - do not edit by hand.
# disease={disease}  variant={variant}  seed={seed}
  input:
    adjacency: [{adjacency}]
    adjacency_field: [{adjacency_field}]
    tag: {tag}
    use_expression: False
    datasets: {datasets}

  model:
    mp:
       type: film
       n_layers: 2
    pre_mp:
      dim: 50
      n_layers: 5
    post_mp:
      dim: 50
      n_layers: 5

  crossval:
    mode: kfold
    n_folds: 5
    positive_only: True
    seed: {seed}

  inference:
    save_dir: ./results/
    save_sorted: True
    save_tsv: True
"""


def derive_missing_ground_truth(disease_dir, dry_run=False):
    """Write AD/AR DEE 2022-09 lists if absent."""
    written = []
    for key, (base_file, diff_file, out_file) in DERIVED.items():
        out_path = os.path.join(disease_dir, out_file)
        if os.path.exists(out_path):
            continue
        base_path = os.path.join(disease_dir, base_file)
        diff_path = os.path.join(disease_dir, diff_file)
        if not (os.path.exists(base_path) and os.path.exists(diff_path)):
            print("  [skip] {}: missing {} or {}".format(key, base_file, diff_file))
            continue
        read = lambda p: {l.strip() for l in open(p) if l.strip()}
        base, diff = read(base_path), read(diff_path)
        if not diff <= base:
            print("  [warn] {}: diff is not a subset of the later list; "
                  "derivation may be wrong".format(key))
        pre = sorted(base - diff)
        if not dry_run:
            with open(out_path, "w") as handle:
                handle.write("\n".join(pre) + "\n")
        written.append((out_file, len(pre)))
        print("  derived {} ({} genes = {} - {})".format(out_file, len(pre), len(base), len(diff)))
    return written


def build_mapping(disease_dir_rel, disease_dir_abs):
    """One extensions/mapping.json entry per disease.

    Returns (entries, keys) where keys are the bare disease keys that got an
    entry. Callers need the bare keys: entry names carry GT_PREFIX, so matching
    a disease key straight against the names silently matches nothing.
    """
    mapping = []
    keys = []
    for key, (gt_file, _) in DISEASES.items():
        if not os.path.exists(os.path.join(disease_dir_abs, gt_file)):
            print("  [skip] {}: {} not found".format(key, gt_file))
            continue
        # Prefix the tag so no disease name is a SUBSTRING of another. The
        # Mapper selects with `tag.lower() in mapping[field].lower()`, so a bare
        # "dee" would also match "ad_dee" and "ar_dee" and silently pull in three
        # ground truths, of which PreProcessor then uses whichever sorts first.
        mapping.append({
            "name": GT_PREFIX + key,
            "ground_truth": GT_PREFIX + key,
            "features_file": "",
            "function": "test_preprocess_labels",
            "args": [os.path.join(disease_dir_rel, gt_file)],
            "kwargs": {},
        })
        keys.append(key)
    return mapping, keys


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(os.path.join(here, "..", ".."))
    speos = os.path.join(root, "external", "SPEOS")
    disease_abs = os.path.join(root, "data", "kiml_data", "diseases")
    # Paths inside SPEOS configs are resolved relative to external/SPEOS.
    disease_rel = "./../../data/kiml_data/diseases"

    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seeds", type=int, default=5,
                        help="repeats per disease x variant, for run-to-run variance (default 5)")
    parser.add_argument("--diseases", nargs="*", default=sorted(DISEASES))
    parser.add_argument("--variants", nargs="*", default=["GNN", "CGNN", "KIGNN"],
                        help="subset of {}".format(sorted(VARIANTS)))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    print("Deriving missing ground-truth lists...")
    derive_missing_ground_truth(disease_abs, args.dry_run)

    print("\nBuilding extensions/mapping.json...")
    mapping, known = build_mapping(disease_rel, disease_abs)
    mapping_path = os.path.join(speos, "extensions", "mapping.json")
    if not args.dry_run:
        with open(mapping_path, "w") as handle:
            json.dump(mapping, handle, indent=2)
    print("  {} entries -> {}".format(len(mapping), mapping_path))

    config_dir = os.path.join(speos, "configs")
    manifest = []
    generated = []

    stale = [f for f in os.listdir(config_dir)
             if f.startswith("Rev_") and f.endswith(".yaml")]
    if stale:
        print("  removing {} stale generated config(s)".format(len(stale)))
        if not args.dry_run:
            for name in stale:
                os.remove(os.path.join(config_dir, name))

    print("\nWriting configs...")
    for disease in args.diseases:
        if disease not in known:
            print("  [skip] {}: no mapping entry".format(disease))
            continue
        generated.append(disease)
        for variant in args.variants:
            datasets, adjacency = VARIANTS[variant]
            for seed in range(1, args.seeds + 1):
                name = "Rev_{}_{}_s{}".format(disease, variant, seed)
                body = CONFIG_TEMPLATE.format(
                    name=name,
                    disease=disease,
                    variant=variant,
                    seed=seed,
                    tag=GT_PREFIX + disease,
                    datasets=datasets,
                    adjacency=", ".join('"{}"'.format(a) for a in adjacency),
                    adjacency_field=", ".join('"name"' for _ in adjacency),
                )
                if not args.dry_run:
                    with open(os.path.join(config_dir, name + ".yaml"), "w") as handle:
                        handle.write(body)
                manifest.append(name)

    manifest_path = os.path.join(speos, "revision_manifest.txt")
    if not args.dry_run:
        with open(manifest_path, "w") as handle:
            handle.write("\n".join(manifest) + "\n")

    print("  {} configs ({} diseases x {} variants x {} seeds)".format(
        len(manifest), len(generated), len(args.variants), args.seeds))
    skipped = [d for d in args.diseases if d not in generated]
    if skipped:
        print("  [skipped diseases] {}".format(", ".join(skipped)))
    print("  manifest -> {}".format(manifest_path))
    print("\nSubmit with:")
    print("  sbatch --array=0-{} additional_experiments/revision_runs/run_revision.slurm".format(
        max(len(manifest) - 1, 0)))
    print("\nRun ONE job first and check it reproduces the published number before")
    print("submitting the whole array (see run_revision.slurm header).")


if __name__ == "__main__":
    main()
